  const SomaliMaterialFallback();
  @override
  bool isSupported(Locale l) => l.languageCode == 'so';
  @override
  Future<MaterialLocalizations> load(Locale l) => DefaultMaterialLocalizations.load(l);
  @override
  bool shouldReload(SomaliMaterialFallback old) => false;
}

