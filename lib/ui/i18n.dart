/// App language (PLAN.md 3.4). Follows the phone by default: Somali, Arabic or English, with full right-to-left for Arabic.
/// Strings are keyed by their English text: `tr('Settings')`. A missing translation falls back to English.
/// This is the app's own words only; the reply language is a separate setting.
class AppLang extends ChangeNotifier {
  AppLang._();
  static final I = AppLang._();

  static const supported = ['so', 'ar', 'en'];
  static const _key = 'ui_language';

  /// 'phone' or one of [supported].
  String choice = 'phone';

  /// The language in use right now.
  String get code {
    if (supported.contains(choice)) return choice;
    final phone = PlatformDispatcher.instance.locale.languageCode;
    return supported.contains(phone) ? phone : 'en';
  }

  Locale get locale => Locale(code);
  bool get rtl => code == 'ar';

  Future<void> load() async {
    try {
      final p = await SharedPreferences.getInstance();
      choice = p.getString(_key) ?? 'phone';
    } catch (_) {}
    notifyListeners();
  }

  Future<void> set(String c) async {
    choice = c;
    notifyListeners();
    // Screens already open read their words at build time; rebuild them all so nothing stays in the old language.
    WidgetsBinding.instance.addPostFrameCallback((_) {
      void mark(Element e) {
        e.markNeedsBuild();
        e.visitChildren(mark);
      }
      WidgetsBinding.instance.rootElement?.visitChildren(mark);
    });
    try {
      final p = await SharedPreferences.getInstance();
      await p.setString(_key, c);
    } catch (_) {}
  }

  /// Language names in their own language.
  static const names = {'phone': 'Same as phone', 'so': 'Soomaali', 'ar': 'العربية', 'en': 'English'};
}

/// The app's own words in the current language. `{name}`-style holes are filled from [args].
String tr(String en, [Map<String, String> args = const {}]) {
  var s = Strings.table[AppLang.I.code]?[en] ?? en;
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// Material has no Somali; it uses the English widget words (dates, "OK", tooltips) left to right.
